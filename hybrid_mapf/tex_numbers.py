"""Write every number quoted in the slides/report as LaTeX macros, straight from the result files,
so nothing is transcribed by hand. Output: talk/final/numbers.tex"""
import json
import os
import re

import pandas as pd

ROOT = os.path.join(os.path.dirname(__file__), "..")
ART = os.path.join(ROOT, "artifacts")
DST = os.path.join(ROOT, "talk", "final", "numbers.tex")


def name(*parts):
    # LaTeX macro names: letters only
    words = re.sub(r"[^A-Za-z0-9]+", " ", " ".join(map(str, parts))).split()
    num = {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six",
           "7": "seven", "8": "eight", "9": "nine"}
    out = ""
    for w in words:
        out += "".join(num[c] if c.isdigit() else c for c in w).capitalize()
    return "\\" + out


def main():
    lines = []
    put = lambda k, v: lines.append(f"\\newcommand{{{k}}}{{{v}}}")
    gd = json.load(open(os.path.join(ART, "gate.json")))
    put("\\ValAucGate", f"{gd['val_auc']:.3f}")
    put("\\ValAucConf", f"{gd['val_auc_conf']:.3f}")
    put("\\GateRecall", f"{gd.get('recall', 0.9):.2f}")
    put("\\GateHold", gd["hold"])
    log = open(os.path.join(ART, "train_log.txt")).read()
    put("\\PolicyAcc", f"{100 * float(re.findall(r'val acc ([0-9.]+)', log)[-1]):.1f}")
    n_samples = int(re.search(r"samples train=(\d+)", log).group(1))
    put("\\ExpertSamples", f"{n_samples:,}".replace(",", "{,}"))
    put("\\ROrder", json.load(open(os.path.join(ART, "r_order.json")))["R"])

    df = pd.read_csv(os.path.join(ART, "results.csv"))
    main_ = df[~df.method.str.endswith("_sweep")]
    for (m, N), d in main_.groupby(["method", "N"]):
        put(name("succ", m, N), f"{d.success.mean():.2f}")
        put(name("rate", m, N), f"{100 * d.search_rate.mean():.0f}")
        put(name("time", m, N), f"{d.runtime.mean():.2f}")
    for m, d in main_.groupby("method"):
        put(name("succ", m, "all"), f"{d.success.mean():.2f}")
        put(name("rate", m, "all"), f"{100 * d.search_rate.mean():.0f}")
        put(name("lacamcalls", m, "all"), f"{d.n_lacam.mean():.2f}")
    cs = main_[main_.method == "cspibt"].groupby("N").n_cspibt.mean()
    gl = main_[main_.method == "gate_lacam"].groupby("N").n_cspibt.mean()
    save = 100 * (1 - gl / cs)
    put("\\CallSaveMin", f"{save.min():.0f}")
    put("\\CallSaveMax", f"{save.max():.0f}")
    s = pd.read_csv(os.path.join(ART, "summary.csv"))
    for _, r in s.dropna(subset=["subopt_common"]).iterrows():
        put(name("subopt", r.method, r.N), f"{r.subopt_common:.2f}")
    with open(DST, "w") as f:
        f.write("% generated by hybrid_mapf/tex_numbers.py -- do not edit by hand\n")
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(lines)} macros to {DST}")


if __name__ == "__main__":
    main()
